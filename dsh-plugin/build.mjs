// No install, no profile access. Node >=24 supplies the TypeScript eraser.
import { stripTypeScriptTypes } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
const check = process.argv.includes('--check');
for (const name of ['index', 'bridge']) {
 const source = new URL('./src/' + name + '.ts', import.meta.url);
 const destination = new URL('./lib/' + name + '.js', import.meta.url);
 const output = '// Generated by node build.mjs; do not edit.\n' + stripTypeScriptTypes(readFileSync(source, 'utf8').replace(/\r\n/g, '\n'), { mode: 'strip' }).replace(/[ \t]+$/gm, '');
 if (check) {
  if (readFileSync(destination, 'utf8') !== output) throw new Error('Stale lib/' + name + '.js');
 } else writeFileSync(destination, output, 'utf8');
}
console.log(check ? 'src/lib match' : 'built lib/index.js and lib/bridge.js');
